def random_words(n=50):
    """随机抽取 n 个触发词（词数不足时全部返回，顺序随机）。"""
    keys = list(POOL)
    if len(keys) <= n:
        random.shuffle(keys)
        return keys
    return random.sample(keys, n)


def explain(word):
    """返回某触发词的内容列表；未收录返回 None。支持完全匹配与包含匹配。"""
    word = (word or "").strip()
    if not word:
        return None
    if word in POOL:
        return POOL[word]
    # 包含匹配：优先最长的命中词
    hits = [w for w in POOL if w in word or word in w]
    if not hits:
        return None
    hits.sort(key=len, reverse=True)
    return POOL[hits[0]]
